def get_benchmark_dataset() -> List[Dict[str, Any]]:
    """Return complete benchmark dataset, ensuring both 'query' and 'question' aliases exist."""
    for case in BENCHMARK_CASES:
        if "query" not in case and "question" in case:
            case["query"] = case["question"]
        elif "question" not in case and "query" in case:
            case["question"] = case["query"]
    return BENCHMARK_CASES


